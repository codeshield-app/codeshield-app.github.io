/* CodeShield — printable report. Rendered into a hidden iframe and printed;
   the browser's "Save as PDF" turns it into a PDF with proper Arabic shaping. */
const esc = s => String(s ?? "").replace(/[&<>"']/g, c => ({ "&":"&amp;", "<":"&lt;", ">":"&gt;", '"':"&quot;", "'":"&#39;" }[c]));

export function buildReportHTML(scan, lang){
  const ar = lang === "ar";
  const T = (en, a) => ar ? a : en;
  const sev = s => ar ? ({ HIGH:"عالية", MEDIUM:"متوسطة", LOW:"منخفضة" }[s]) : s;
  const st = f => !f.verify ? T("Test generated (not verified)", "تم توليد الاختبار (لم يُتحقَّق)")
    : f.verify.status === "verified" ? T("✓ Fix verified", "✓ تم التحقق من الإصلاح") : T("✗ Not verified", "✗ لم يتحقق");
  const s = scan.summary;
  const rows = scan.findings.map((f, i) => `
    <section class="f">
      <h3>${i + 1}. ${esc(ar ? f.name_ar : f.name_en)} <span class="sev ${f.severity.toLowerCase()}">${sev(f.severity)}</span></h3>
      <div class="meta ltr">${esc(f.cwe)} · ${esc(f.owasp)} · ${f.file ? esc(f.file) + " : " : T("line ", "سطر ")}${f.line}</div>
      <div class="lbl">${T("Vulnerable line", "السطر المصاب")}</div><pre class="bad">${esc(f.snippet)}</pre>
      <p>${esc(ar ? f.why_ar : f.why_en)}</p>
      <div class="lbl">${T("Fix", "الإصلاح")}</div><p>${esc(ar ? f.fix_ar : f.fix_en)}</p>
      ${f.patch && f.patch.trim() !== f.raw.trim() ? `<pre class="good">${esc(f.patch.trim())}</pre>` : ""}
      <div class="lbl">${T("Verification", "التحقق")}: <b>${st(f)}</b></div>
      ${f.verify ? `<pre class="ev">${f.verify.evidence.map(e => `[${e.t}] ${e.step} → ${e.result}`).join("\n")}</pre>` : ""}
    </section>`).join("");
  return `<!DOCTYPE html><html lang="${lang}" dir="${ar ? "rtl" : "ltr"}"><head><meta charset="utf-8">
<title>CodeShield report</title>
<link href="https://fonts.googleapis.com/css2?family=Cairo:wght@400;700;800&family=JetBrains+Mono&display=swap" rel="stylesheet">
<style>
  @page{ size:A4; margin:16mm 14mm; }
  body{ font-family:Cairo,Arial,sans-serif; color:#172033; font-size:12px; line-height:1.7; }
  .ltr, pre{ direction:ltr; text-align:left; unicode-bidi:isolate; }
  header{ display:flex; justify-content:space-between; align-items:flex-end; border-bottom:3px solid #2f7ec2; padding-bottom:10px; margin-bottom:16px; }
  h1{ font-size:24px; margin:0; color:#2f7ec2; letter-spacing:1px; direction:ltr; }
  h2{ font-size:15px; margin:18px 0 8px; }
  .kpis{ display:grid; grid-template-columns:repeat(5,1fr); gap:8px; margin:10px 0 6px; }
  .k{ border:1px solid #dde3ee; border-radius:8px; padding:8px; text-align:center; }
  .k b{ display:block; font-size:20px; }
  .f{ border:1px solid #dde3ee; border-radius:8px; padding:10px 12px; margin-bottom:10px; page-break-inside:avoid; }
  .f h3{ font-size:13.5px; margin:0 0 2px; }
  .meta{ color:#55627a; font-size:10.5px; }
  .lbl{ font-weight:800; margin-top:6px; font-size:11px; color:#55627a; }
  pre{ font-family:"JetBrains Mono",monospace; font-size:10.5px; background:#f3f6fb; border-radius:6px; padding:6px 8px; white-space:pre-wrap; word-break:break-word; margin:4px 0; }
  pre.bad{ border-inline-start:3px solid #d43d63; } pre.good{ border-inline-start:3px solid #1f9d6b; } pre.ev{ color:#55627a; }
  .sev{ font-size:10px; padding:2px 8px; border-radius:99px; margin-inline-start:6px; }
  .sev.high{ background:#fde7ed; color:#d43d63; } .sev.medium{ background:#fdf3e1; color:#b7791f; } .sev.low{ background:#eef1f5; color:#55627a; }
  footer{ margin-top:16px; color:#55627a; font-size:10px; border-top:1px solid #dde3ee; padding-top:8px; }
</style></head><body>
<header><div><h1>CODESHIELD</h1><div>${T("Security scan report", "تقرير الفحص الأمني")}</div></div>
<div class="ltr" style="text-align:end;color:#55627a">${esc(scan.label)}<br>${new Date().toLocaleString(ar ? "ar-SA" : "en-GB")}</div></header>
<div class="kpis">
  <div class="k"><b>${scan.score}</b>${T("Security score", "مؤشر الأمان")}</div>
  <div class="k"><b>${s.total}</b>${T("Findings", "الثغرات")}</div>
  <div class="k"><b style="color:#d43d63">${s.HIGH}</b>${T("High", "عالية")}</div>
  <div class="k"><b style="color:#b7791f">${s.MEDIUM}</b>${T("Medium", "متوسطة")}</div>
  <div class="k"><b style="color:#1f9d6b">${s.verified}</b>${T("Fixes verified", "إصلاحات مُتحقَّقة")}</div>
</div>
<div style="color:#55627a">${T("Scanned", "تم فحص")} ${scan.lines} ${T("lines", "سطر")}${scan.files > 1 ? ` · ${scan.files} ${T("files", "ملف")}` : ""} · ${T("engine", "المحرك")} v${scan.engine}</div>
<h2>${T("Findings", "الثغرات")}</h2>
${rows || `<p>${T("No findings matched the active rules.", "لم تطابق أي ثغرة القواعد الفعّالة.")}</p>`}
<footer>${T("Generated by CodeShield in the browser. Rule-based static analysis: it does not follow data flow across lines, so a clean report is not a guarantee of security.",
  "أُنشئ بواسطة كودشيلد داخل المتصفح. تحليل ساكن بالقواعد لا يتتبّع تدفّق البيانات عبر الأسطر، لذلك التقرير النظيف ليس ضمانًا كاملًا للأمان.")}</footer>
</body></html>`;
}

export function printReport(scan, lang){
  const frame = document.getElementById("printFrame");
  const doc = frame.contentDocument;
  doc.open(); doc.write(buildReportHTML(scan, lang)); doc.close();
  const go = () => { frame.contentWindow.focus(); frame.contentWindow.print(); };
  (doc.fonts ? doc.fonts.ready : Promise.resolve()).then(() => setTimeout(go, 250));
}
